import Foundation

/// The failures the app is allowed to report, as a stable code plus a fixed
/// sentence (S5).
///
/// Sentry must never receive the description of an upstream error: a Supabase
/// `AuthError` or a `URLError` description can embed the raw HTTP body, and the
/// body of a failed request carries the signed-in email. Reporting one of these
/// cases instead keeps the dashboard useful (the code groups the issue) without
/// sending anything the user typed.
enum CrashReport: Error, Equatable, CaseIterable {

    /// The Apple token exchange with Supabase failed.
    case authSignInFailed

    /// Dropping the Supabase session failed.
    case authSignOutFailed

    /// The native Sign in with Apple sheet failed (cancelling is not a failure).
    case appleSignInFailed

    /// Stable identifier of the issue. It must not change when a message is
    /// reworded: it is what the dashboard groups by.
    var code: String {
        switch self {
        case .authSignInFailed:
            return "auth.signInFailed"
        case .authSignOutFailed:
            return "auth.signOutFailed"
        case .appleSignInFailed:
            return "appleSignIn.failed"
        }
    }

    /// Sentence the event carries. It holds no value of the failure.
    var message: String {
        switch self {
        case .authSignInFailed:
            return "Signing in with Apple failed."
        case .authSignOutFailed:
            return "Signing out failed."
        case .appleSignInFailed:
            return "The Apple credential request failed."
        }
    }

    /// What is actually sent: the code first, so the fixed sentence can never
    /// be mistaken for the grouping key.
    var reportedText: String {
        code + ": " + message
    }
}

/// Keeps everything that is not one of our own reports out of Sentry (S5).
///
/// The app reports through `CrashReport`, but the SDK still builds an event from
/// whatever it is handed and can pick up text from elsewhere (an `NSError`
/// description, a request body, a screen name). This is the single rule that
/// decides which text survives, so it is a pure function and it is tested.
enum CrashReportSanitizer {

    /// Bucket of every text the app did not produce itself: one issue in the
    /// dashboard for "something failed and we refuse to say what", which is the
    /// only safe answer for an unknown description.
    static let fallbackCode = "drivy.handledFailure"

    /// Text sent in place of anything that is not our own report.
    static let fallbackText = fallbackCode + ": A failure was reported without details."

    /// Exception type of a sanitized handled failure, so it never groups with a
    /// system crash (those keep their own type and value: they are generated by
    /// the OS and carry no user text).
    static let exceptionType = "CrashReport"

    /// The text itself when the app produced it, the fallback otherwise.
    static func sanitizedMessage(for text: String?) -> String {
        guard let text = text, isOwn(text) else { return fallbackText }
        return text
    }

    /// True when `text` was produced by `CrashReport` (or is the fallback).
    static func isOwn(_ text: String) -> Bool {
        if text == fallbackText {
            return true
        }
        return CrashReport.allCases.contains { text.hasPrefix($0.code) }
    }
}
