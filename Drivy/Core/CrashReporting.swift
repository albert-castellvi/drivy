import Foundation
import Sentry

/// The only place the app talks to the Sentry SDK (S3, S5).
///
/// Everything else injects these functions, so the auth flow stays testable
/// without a started SDK, and the rest of the app never imports `Sentry`.
enum CrashReporting {

    /// Starts the SDK at launch so crashes, app hangs, handled errors and
    /// session health are reported (S3).
    ///
    /// Debug builds never start it (S5): developer and tester crashes, hangs and
    /// sessions would land in the production project next to the signed-in id.
    /// Only the start call is gated, so `configure` is still compiled by every
    /// pull-request build and a renamed SDK option fails there instead of in the
    /// release archive.
    static func start() {
        #if DEBUG
        let shouldStart = false
        #else
        // Unit tests run inside the app process (TEST_HOST). A started SDK
        // would reach the network and mix test failures with real data.
        let shouldStart = ProcessInfo.processInfo.environment["XCTestConfigurationFilePath"] == nil
        #endif

        guard shouldStart else { return }

        SentrySDK.start { options in
            configure(options)
        }
    }

    /// Everything the SDK is allowed to send (S3, S5). Crash, app hang and auto
    /// session tracking are left at the SDK defaults.
    private static func configure(_ options: Sentry.Options) {
        options.dsn = DrivyConfig.sentryDSN
        options.environment = environmentName

        // S5: no personal data, not even the ones the SDK would infer.
        options.sendDefaultPii = false

        // No request breadcrumbs, no captured HTTP client errors: a URL can carry
        // a path, a query parameter or a fragment of a response body.
        options.enableNetworkBreadcrumbs = false
        options.enableCaptureFailedRequests = false

        // Swizzling is what adds the touch, navigation and view-controller
        // breadcrumbs, and with them the name of the screen the user was on.
        options.enableSwizzling = false

        // Attachments are off for the same reason: a screenshot or a view
        // hierarchy of a driving screen is location data.
        options.attachScreenshot = false
        options.attachViewHierarchy = false

        options.tracesSampleRate = 0.2

        // Last line of defence (S5): whatever reaches the SDK, only the sanitized
        // payload leaves the device.
        options.beforeSend = { event in
            CrashReporting.sanitize(event)
        }
    }

    /// Reports a handled failure as a stable code with a fixed sentence (S5).
    ///
    /// Only a `CrashReport` may be sent. Any other `Error` would go out with its
    /// `localizedDescription`, and a Supabase or `URLError` description can
    /// embed the response body, so it is replaced by the fallback code.
    /// A no-op while the SDK is not started, which is the unit test case.
    static func capture(_ error: Error) {
        guard let report = error as? CrashReport else {
            SentrySDK.capture(message: CrashReportSanitizer.fallbackText)
            return
        }
        SentrySDK.capture(message: report.reportedText)
    }

    /// Sets the signed-in user id, or clears it when `nil` (S4).
    ///
    /// Only the Supabase id is sent: never the email.
    static func setUser(id: String?) {
        guard let id = id else {
            SentrySDK.setUser(nil)
            return
        }
        // Fully qualified on purpose: Supabase also exports a `User` type.
        SentrySDK.setUser(Sentry.User(userId: id))
    }

    // MARK: - Sanitizing

    /// Removes everything that could identify the user beyond the pseudonymous
    /// Supabase id before the event is serialized (S5).
    ///
    /// A system crash keeps its own exception values: those are generated by the
    /// OS, they are what groups the crash and they carry no text of ours. A
    /// handled error does not get that treatment, because the SDK builds it from
    /// the error's description, so its message and exception values become ours.
    private static func sanitize(_ event: Sentry.Event) -> Sentry.Event? {
        event.request = nil
        event.user = sanitizedUser(event.user)

        if let error = event.error {
            // The SDK builds the event from the error's description, and every
            // value of a chain comes from the same description, so the whole chain
            // collapses into one sanitized exception.
            let text = CrashReportSanitizer.sanitizedMessage(for: (error as? CrashReport)?.reportedText)
            event.message = SentryMessage(formatted: text)

            if let first = event.exceptions?.first {
                first.value = text
                first.type = CrashReportSanitizer.exceptionType
                event.exceptions = [first]
            }
            return event
        }

        if let message = event.message {
            event.message = SentryMessage(
                formatted: CrashReportSanitizer.sanitizedMessage(for: message.formatted)
            )
        }

        return event
    }

    /// Keeps the id of the user and drops the rest of the profile the SDK may have
    /// attached (email, username, IP, geo, free-form data).
    private static func sanitizedUser(_ user: Sentry.User?) -> Sentry.User? {
        guard let id = user?.userId else { return nil }
        return Sentry.User(userId: id)
    }

    // MARK: - Environment

    /// `testflight` for a sandbox receipt (the App Store receipt a TestFlight
    /// build carries) and `production` for an App Store build. Debug builds do
    /// not start the SDK, so there is no `debug` environment any more (S5).
    private static var environmentName: String {
        if Bundle.main.appStoreReceiptURL?.lastPathComponent == "sandboxReceipt" {
            return "testflight"
        }
        return "production"
    }
}
